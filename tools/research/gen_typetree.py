# Generates engine/typetree_<name>_2021_3.inc: the type tree of a class for Unity 2021.3.18 from the
# type database UnityPy carries (TPK), for the device's type-tree reader/writer (M4c). Player builds
# strip type trees, so the layout has to be built in. Structural data only.
# Usage: python3 -I gen_typetree.py <class id> <class name> > engine/typetree_<name>_2021_3.inc
#   48 Shader, 141 BuildSettings
import sys
import UnityPy.helpers.Tpk as Tpk

class_id, class_name = int(sys.argv[1]), sys.argv[2]
node = Tpk.get_typetree_node(class_id, (2021, 3, 18, 0))
rows = []


def walk(n, depth):
    rows.append((depth, n.m_Type, n.m_Name, n.m_ByteSize, n.m_MetaFlag))
    for c in n.m_Children or []:
        walk(c, depth + 1)


walk(node, 0)
print('// SPDX-License-Identifier: GPL-3.0-or-later')
print(f'// Generated by tools/research/gen_typetree.py: class {class_id} ({class_name}), Unity 2021.3.18, from UnityPy\'s type')
print('// database. One row per node in depth-first order: depth, type, name, byte size (-1: variable), meta flags.')
for d, t, nm, sz, mf in rows:
    print(f'{{{d}, "{t}", "{nm}", {sz}, {mf:#x}}},')
